export type Tr = ((en: string, he: string) => string) & {
  t: <A>(fn: (a: A) => Record<Lang, string>, arg: A) => string;
};

export function makeTr(lang: string): Tr {
  const l = (lang in { he: 1, en: 1, fr: 1, de: 1, es: 1, it: 1, ru: 1 } ? lang : 'en') as Lang;
  const fn = ((en: string, he: string) => (l === 'he' ? he : D[l]?.[en] ?? en)) as Tr;
  fn.t = (f, a) => f(a)[l];
  return fn;
}

